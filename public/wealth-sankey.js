/* UX-025: client-side Sankey. Every input comes from the existing cash ledger.
   No account data, persistence changes, third-party libraries or remote calls. */
(function () {
  'use strict';
  var state = { period: 'month', view: 'diagram', chosen: null, flows: [] };
  var money = function (v) {
    return new Intl.NumberFormat('de-DE', { style: 'currency', currency: 'EUR',
      maximumFractionDigits: 0 }).format(v);
  };
  var safe = function (s) {
    return String(s).replace(/[&<>"']/g, function (ch) {
      return {'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;','"':'&quot;'}[ch];
    });
  };
  function build(x, c) {
    var income = [], use = [], epsilon = 0.00001;
    function add(kind, id, name, amount, color, detail) {
      if (!Number.isFinite(amount) || amount <= epsilon) return;
      (kind === 'source' ? income : use).push({
        kind: kind, id: id, name: name, value: amount,
        color: color, detail: detail
      });
    }
    var net = Number(c.net) || 0, sales = Number(c.sold) || 0;
    var rental = Number(c.rentalCash) || 0, tax = Number(c.taxProvision) || 0;
    var payment = Math.max(0, (Number(c.housing) || 0) - (Number(x.owner) || 0));
    var interest = Math.min(payment, Math.max(0, (Number(x.loan) || 0) *
      (Number(x.rate) || 0) / 1200));
    var principal = Math.max(0, payment - interest) + (Number(x.extra) || 0) / 12;
    var residual = Number(c.free) || 0;
    add('source', 'takehome', 'Household take-home', Math.max(0, net), '#177f6b',
      'Net household income after modeled payroll deductions. Gross taxes are not deducted again.');
    add('source', 'sales', 'ETF share sales', Math.max(0, sales), '#7866af',
      'Proceeds from selling existing ETF units; this is not salary or investment profit.');
    add('source', 'rental', 'Rental net receipts', Math.max(0, rental), '#3995a5',
      'Net cash generated by selected rentals after their regular expenses and debt service.');
    add('source', 'taxcredit', 'Rental tax timing credit', Math.max(0, -tax), '#7c976b',
      'Illustrative tax credit recognized only in accrual mode; not guaranteed monthly cash.');
    add('source', 'gap', 'Funding gap', Math.max(0, -residual), '#c6585f',
      'The selected monthly allocations exceed available cash. This is missing funding, not income.');

    add('use', 'rent', 'Rent & owner costs', Math.max(0, Number(x.owner) || 0), '#3f86ad',
      'Rent or recurring owner costs; excludes separately identified mortgage interest and principal.');
    add('use', 'interest', 'Mortgage interest', interest, '#c38a58',
      'Mortgage interest is a financing cost. Principal is shown separately.');
    add('use', 'principal', 'Mortgage principal', principal, '#57a3ba',
      'Mortgage principal and extra repayments reduce debt and may build equity, not a consumption expense.');
    add('use', 'living', 'Living expenses', Math.max(0, Number(c.living) || 0), '#c79d5c',
      'Food, transport, utilities not counted in rent, insurance, lifestyle and other routine spending.');
    add('use', 'otherdebt', 'Other debt payments', Math.max(0, Number(c.otherDebt) || 0), '#c86d6b',
      'The current ledger groups other loan payments; principal and interest are not separately modeled.');
    add('use', 'etfbuy', 'ETF contributions', Math.max(0, Number(c.invested) || 0), '#806cb5',
      'Purchases of ETF units: asset allocation rather than consumption.');
    add('use', 'cashsave', 'Cash savings', Math.max(0, Number(c.monthlySaving) || 0), '#9d8a44',
      'Transfer of free money into cash savings; does not leave household net worth.');
    add('use', 'rentaldeficit', 'Rental funding shortfall', Math.max(0, -rental), '#b56883',
      'Negative rental cash flow requires support from the other household income sources.');
    add('use', 'taxprovision', 'Rental tax provision', Math.max(0, tax), '#a87454',
      'Accrual-mode estimate; tax authority settlement can occur later.');
    add('use', 'negativeincome', 'Negative income adjustment', Math.max(0, -net), '#bc6577',
      'A negative modeled net-income entry is treated as an outflow.');
    add('use', 'negativeSales', 'ETF withdrawal shortfall', Math.max(0, -sales), '#aa778a',
      'Signed adjustment for negative ETF proceeds, if any.');
    add('use', 'free', 'Unallocated cash', Math.max(0, residual), '#149676',
      'Cash still available after all selected spending, debt repayments and savings transfers.');

    // The canonical identity is: net + sales + rental - tax = total uses + free.
    var totalIn = income.reduce(function (a, b) {return a + b.value;}, 0);
    var totalOut = use.reduce(function (a, b) {return a + b.value;}, 0);
    var delta = totalIn - totalOut;
    if (Math.abs(delta) > epsilon) {
      // Do not hide missing accounting adjustments as an invented expense.
      // Expose any unexpected discrepancy and render no diagram until fixed.
      return {income: income, use: use, totalIn: totalIn, totalOut: totalOut,
        delta: delta, balanced: false, free: residual};
    }
    return {income: income, use: use, totalIn: totalIn, totalOut: totalOut,
      delta: delta, balanced: true, free: residual};
  }
  function ribbon(x1, y1, x2, y2, h) {
    var bend = (x2 - x1) * 0.53;
    return 'M'+x1+','+y1+' C'+(x1+bend)+','+y1+' '+(x2-bend)+','+y2+' '+x2+','+y2+
      ' L'+x2+','+(y2+h)+' C'+(x2-bend)+','+(y2+h)+' '+(x1+bend)+','+(y1+h)+
      ' '+x1+','+(y1+h)+' Z';
  }
  function chart(data, factor) {
    var sources=data.income, sinks=data.use, total=data.totalIn*factor;
    if (total < 0.001) return '<p class="sankey-empty">Enter household income or planned spending to see your money flow.</p>';
    var height = Math.max(410, 118 + Math.max(sources.length, sinks.length) * 57);
    var yPadding=54, gap=12, free=Math.max(1,height-2*yPadding);
    var scale = Math.min(
      (free - gap*Math.max(0,sources.length-1))/total,
      (free - gap*Math.max(0,sinks.length-1))/total
    );
    var srcHeight=sources.reduce(function (a,v) {return a+v.value*factor*scale;}, 0)+gap*Math.max(0,sources.length-1);
    var sinkHeight=sinks.reduce(function (a,v) {return a+v.value*factor*scale;}, 0)+gap*Math.max(0,sinks.length-1);
    var aTop=(height-srcHeight)/2, bTop=(height-sinkHeight)/2;
    var centerTop=(height-total*scale)/2;
    var svg='<svg class="sankey-svg" viewBox="0 0 1000 '+height+
      '" xmlns="http://www.w3.org/2000/svg" role="group" aria-label="Cash flow Sankey from sources through pooled cash to allocations">';
    var leftOffset=0, rightOffset=0, ay=aTop, by=bTop;
    svg+='<rect class="sankey-pool" x="487" y="'+centerTop.toFixed(2)+'" width="18" height="'+(total*scale).toFixed(2)+'" rx="4"/>';
    svg+='<text class="sankey-center-label" x="496" y="'+Math.max(22,centerTop-18)+'" text-anchor="middle">ALLOCATED CASH</text>';
    state.flows=[];
    sources.forEach(function (f) {
      var amount=f.value*factor,h=amount*scale;
      var d=ribbon(49,ay,487,centerTop+leftOffset,h);
      svg+='<path class="sankey-link" data-sankey-id="'+f.id+'" tabindex="0" role="button" aria-label="'+
        safe(f.name+' '+money(amount))+'" d="'+d+'" fill="'+f.color+'"><title>'+safe(f.name+': '+money(amount))+'</title></path>';
      svg+='<rect x="32" y="'+ay.toFixed(2)+'" width="17" height="'+h.toFixed(2)+'" fill="'+f.color+'" rx="2"/>';
      svg+='<text class="sankey-node-title" x="59" y="'+(ay+h/2-2).toFixed(2)+'">'+safe(f.name)+'</text>';
      svg+='<text class="sankey-node-amount" x="59" y="'+(ay+h/2+13).toFixed(2)+'">'+safe(money(amount))+'</text>';
      state.flows.push(f);
      ay+=h+gap;leftOffset+=h;
    });
    sinks.forEach(function (f) {
      var amount=f.value*factor,h=amount*scale;
      var d=ribbon(505,centerTop+rightOffset,922,by,h);
      svg+='<path class="sankey-link" data-sankey-id="'+f.id+'" tabindex="0" role="button" aria-label="'+
        safe(f.name+' '+money(amount))+'" d="'+d+'" fill="'+f.color+'"><title>'+safe(f.name+': '+money(amount))+'</title></path>';
      svg+='<rect x="922" y="'+by.toFixed(2)+'" width="17" height="'+h.toFixed(2)+'" fill="'+f.color+'" rx="2"/>';
      svg+='<text class="sankey-node-title" x="910" y="'+(by+h/2-2).toFixed(2)+'" text-anchor="end">'+safe(f.name)+'</text>';
      svg+='<text class="sankey-node-amount" x="910" y="'+(by+h/2+13).toFixed(2)+'" text-anchor="end">'+safe(money(amount))+'</text>';
      state.flows.push(f);
      by+=h+gap;rightOffset+=h;
    });
    return svg+'</svg>';
  }
  function render(x,c) {
    var section=document.getElementById('cashSankeyPanel');
    if (!section) return;
    var data=build(x,c), factor=state.period==='year'?12:1;
    var title=state.period==='year'?'annualized (12 × current month)':'per month';
    document.getElementById('sankeyPeriodName').textContent=title;
    var status=document.getElementById('sankeyAccounting');
    status.dataset.balanced=String(data.balanced);
    status.dataset.in=(data.totalIn*factor).toFixed(2);
    status.dataset.out=(data.totalOut*factor).toFixed(2);
    status.textContent=data.balanced?
      'Reconciled: '+money(data.totalIn*factor)+' available = '+money(data.totalOut*factor)+' allocated.':
      'Cannot reconcile monthly sources and allocations (difference '+money(data.delta*factor)+'). Check the cash ledger.';
    status.classList.toggle('sankey-warning',!data.balanced);
    var warning=document.getElementById('sankeyFundingWarning');
    warning.hidden=data.free>=0;
    warning.textContent=data.free<0?
      'Funding gap: '+money(-data.free*factor)+'. This is not income. Adjust expenses, repayments or contributions.':'';
    var rows=data.income.concat(data.use);
    document.getElementById('sankeyTableRows').innerHTML=rows.map(function (f) {
      return '<tr data-sankey-row="'+safe(f.id)+'" data-sankey-kind="'+f.kind+
        '" data-month-value="'+f.value.toFixed(5)+'"><td>'+safe(f.kind==='source'?'Source':'Allocation')+
        '</td><th scope="row">'+safe(f.name)+'</th><td class="numeric">'+safe(money(f.value*factor))+
        '</td><td>'+safe(f.detail)+'</td></tr>';
    }).join('');
    document.getElementById('sankeyTableFoot').innerHTML='<tr><th scope="row" colspan="2">Sources / allocations</th><td class="numeric">'+
      safe(money(data.totalIn*factor))+' / '+safe(money(data.totalOut*factor))+'</td><td>'+
      (data.balanced?'Balanced against the existing household ledger':'Not reconciled')+'</td></tr>';
    document.getElementById('sankeyChart').innerHTML=data.balanced?chart(data,factor):
      '<p class="sankey-empty">Diagram hidden until the underlying ledger reconciles. Review the table.</p>';
    if (state.chosen) {
      var chosen=state.flows.find(function (f) {return f.id===state.chosen;});
      if (chosen) pick(chosen.id);
      else state.chosen=null;
    }
    document.querySelectorAll('[data-sankey-period]').forEach(function (b) {
      b.setAttribute('aria-pressed',String(b.dataset.sankeyPeriod===state.period));
    });
    document.querySelectorAll('[data-sankey-view]').forEach(function (b) {
      b.setAttribute('aria-pressed',String(b.dataset.sankeyView===state.view));
    });
    document.getElementById('sankeyChartScroll').hidden=state.view!=='diagram';
    document.getElementById('sankeyTableWrap').hidden=state.view!=='table';
  }
  function pick(id) {
    var selected=state.flows.find(function (f) {return f.id===id;});
    if (!selected) return;
    state.chosen=id;
    var factor=state.period==='year'?12:1;
    var label=document.getElementById('sankeyDetail');
    label.textContent=selected.name+': '+money(selected.value*factor)+
      (state.period==='year'?' per year (current-month run rate). ':' per month. ')+selected.detail;
    document.querySelectorAll('#sankeyChart [data-sankey-id]').forEach(function (link) {
      link.classList.toggle('selected',link.dataset.sankeyId===id);
    });
  }
  function setup() {
    var panel=document.getElementById('cashSankeyPanel');
    if (!panel) return;
    panel.addEventListener('click',function (e) {
      var period=e.target.closest('[data-sankey-period]'),view=e.target.closest('[data-sankey-view]');
      if (period) {
        state.period=period.dataset.sankeyPeriod;
        if (window.currentSummary) render(window.currentSummary.x,window.currentSummary.c);
      } else if (view) {
        state.view=view.dataset.sankeyView;
        if (window.currentSummary) render(window.currentSummary.x,window.currentSummary.c);
      } else {
        var link=e.target.closest('[data-sankey-id]');if (link) pick(link.dataset.sankeyId);
      }
    });
    panel.addEventListener('focusin',function (e) {
      var link=e.target.closest('[data-sankey-id]');if (link) pick(link.dataset.sankeyId);
    });
    panel.addEventListener('keydown',function (e) {
      if ((e.key==='Enter'||e.key===' ')&&e.target.matches('[data-sankey-id]')) {
        e.preventDefault();pick(e.target.dataset.sankeyId);
      }
    });
    panel.addEventListener('pointerover',function (e) {
      var link=e.target.closest('[data-sankey-id]');if(link)pick(link.dataset.sankeyId);
    });
    if (window.matchMedia&&window.matchMedia('(max-width: 600px)').matches) state.view='table';
  }
  setup();
  window.ImmoPilotCashSankey={build:build,render:render};
})();